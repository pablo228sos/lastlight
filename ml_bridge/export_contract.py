"""Deterministic TypeScript wire types from the actual FastAPI OpenAPI schemas."""

import argparse
import json
from pathlib import Path

from ml_bridge.api import app

ROOT = Path(__file__).resolve().parents[1]


def name(value):
    return value.rsplit("/", 1)[-1].replace("-", "_")


def ts(schema):
    if "$ref" in schema:
        return name(schema["$ref"])
    if "anyOf" in schema:
        return " | ".join(ts(part) for part in schema["anyOf"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts(schema['items'])}>"
    if kind == "object":
        required = schema.get("required", [])
        return (
            "{ "
            + "; ".join(
                json.dumps(key) + ("" if key in required else "?") + ": " + ts(value)
                for key, value in schema.get("properties", {}).items()
            )
            + " }"
            if schema.get("properties")
            else "Record<string, unknown>"
        )
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    document = app.openapi()
    schemas = document["components"]["schemas"]
    content = (
        "// Generated by python -m ml_bridge.export_contract; optional bridge only.\n"
    )
    content += (
        "// Power kW, storage kWh, SOC fractions, UTC timestamps, elapsed hours.\n\n"
    )
    content += (
        "\n\n".join(
            f"export type {name(key)} = {ts(value)}"
            for key, value in sorted(schemas.items())
        )
        + "\n"
    )
    target = ROOT / "docs/ml/bridge.contracts.ts"
    openapi = ROOT / "docs/ml/bridge.openapi.json"
    openapi_content = json.dumps(document, indent=2) + "\n"
    if args.check:
        if (
            target.read_text(encoding="utf8") != content
            or openapi.read_text(encoding="utf8") != openapi_content
        ):
            raise SystemExit("Generated bridge contract drift")
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf8", newline="\n")
        openapi.write_text(openapi_content, encoding="utf8", newline="\n")
    print("Verified wire contracts" if args.check else "Generated wire contracts")


if __name__ == "__main__":
    main()
