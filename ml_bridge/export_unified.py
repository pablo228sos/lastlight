"""Generate the complete optional contract and actual web-client wire types."""

import argparse
import json
from pathlib import Path

from services.simulation.api import app
from ml_bridge.export_contract import name, ts
from ml_bridge.integration import intelligence_openapi


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    document = intelligence_openapi(app)
    content = "// Generated by python -m ml_bridge.export_unified. Do not edit.\n"
    content += (
        "\n\n".join(
            f"export type {name(key)} = {ts(value)}"
            for key, value in sorted(document["components"]["schemas"].items())
        )
        + "\n"
    )
    outputs = {
        root / "docs/unified/openapi.json": json.dumps(document, indent=2) + "\n",
        root / "apps/web/src/lib/intelligenceContracts.ts": content,
    }
    for path, value in outputs.items():
        if args.check:
            if path.read_text(encoding="utf8") != value:
                raise SystemExit(f"Unified contract drift: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(value, encoding="utf8", newline="\n")
    print("Verified unified contract" if args.check else "Generated unified contract")


if __name__ == "__main__":
    main()
