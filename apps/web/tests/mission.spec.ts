test('keyboard and reduced motion work at laptop viewport', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await page.setViewportSize({ width: 1366, height: 768 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await expect(page.getByTestId('enter-lab')).toBeVisible()
  await page.evaluate(() => (document.activeElement as HTMLElement)?.blur())
  await page.keyboard.press('Enter')
  await expect(page.locator('main')).toHaveAttribute('data-phase', 'DISTRICT')
  await page.getByTestId('site-school').focus()
  await page.keyboard.press('Enter')
  await expect(page.locator('main')).toHaveAttribute('data-phase', 'SITE')
  await page.getByTestId('disconnect-grid').click()
  await expect(page.locator('main')).toHaveAttribute('data-phase', 'BLACKOUT')
  await page.getByRole('button', { name: /DATA & METHODS/ }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByTestId('reset-scene').blur()
  await page.keyboard.press('r')
  await expect(page.locator('main')).toHaveAttribute('data-visual-step', '0')
  await saveScreenshot(page, 'laptop-reduced-motion.png')
  expect(errors).toEqual([])
})

test('pointer controls and source geometry switch', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await page.goto('/')
  await page.getByTestId('skip-intro').click()
  await page.getByTestId('site-school').click()
  await page.waitForTimeout(2000)
  await page.getByTestId('layer-power').click()
  await expect(page.getByTestId('layer-power')).toHaveClass(/selected/)
  await page.getByTestId('orbit').click()
  await expect(page.locator('main')).toHaveAttribute('data-shot', 'orbit')
  const canvas = page.locator('canvas')
  const box = await canvas.boundingBox()
  if (!box) throw new Error('Canvas missing')
  await page.mouse.move(box.x + box.width * .55, box.y + box.height * .5)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width * .61, box.y + box.height * .56, { steps: 8 })
  await page.mouse.up()
  await page.mouse.wheel(0, -200)
  await expect(canvas).toBeVisible()
  expect(errors).toEqual([])
})


test('mouse city navigation: right-drag pans original district without changing camera shot', async ({ page }) => {
  await page.setViewportSize({ width: 1366, height: 768 })
  await page.goto('/?capture=1')
  await page.getByTestId('skip-intro').click()
  const main = page.locator('main')
  await expect(main).toHaveAttribute('data-shot', 'district')
  const canvas = page.locator('canvas')
  await expect(canvas).toBeVisible()
  await canvas.evaluate((element: HTMLCanvasElement) => {
    element.dispatchEvent(new CustomEvent('lastlight:capture-lock-pose', {
      detail: { shot: 'district' },
    }))
  })
  await expect.poll(async () => await canvas.getAttribute('data-camera-position')).not.toBeNull()
  const before = (await canvas.getAttribute('data-camera-position'))!.split(',').map(Number)
  const bounds = await canvas.boundingBox()
  if (!bounds) throw new Error('WebGL canvas missing')
  await page.mouse.move(bounds.x + bounds.width * .5, bounds.y + bounds.height * .5)
  await page.mouse.down({ button: 'right' })
  await page.mouse.move(bounds.x + bounds.width * .64, bounds.y + bounds.height * .55, { steps: 10 })
  await page.mouse.up({ button: 'right' })
  await expect.poll(async () => {
    const current = (await canvas.getAttribute('data-camera-position'))?.split(',').map(Number) ?? before
    return Math.hypot(current[0]-before[0], current[1]-before[1], current[2]-before[2])
  }).toBeGreaterThan(.15)
  await expect(main).toHaveAttribute('data-shot', 'district')
  await expect(main).toHaveAttribute('data-phase', 'DISTRICT')
})
