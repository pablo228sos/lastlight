import { test, expect } from '@playwright/test'
import type { Page } from '@playwright/test'

async function school(page: Page) {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await page.getByTestId('skip-intro').click()
  await page.getByTestId('site-school').click()
  await page.getByTestId('disconnect-grid').click()
  await expect(page.getByTestId('physics-panel')).toBeVisible({ timeout: 20000 })
}

test('judge walkthrough explains actual physics, axes, real AI and verified proposals', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await school(page)
  await expect(page.getByTestId('physics-panel')).toContainText('16-hour blackout')
  await expect(page.getByTestId('first-failure')).toHaveText('9.12 h')
  await page.getByTestId('open-analysis').click()
  await expect(page.getByTestId('outage-verdict')).toContainText('6.88 h remain')
  await expect(page.getByTestId('outage-verdict')).toContainText('supply can recover later')
  await expect(page.getByRole('definition').filter({ hasText: '80%' })).toBeVisible()
  await page.getByTestId('start-guide').click()
  await page.getByRole('button', { name: 'NEXT STEP' }).click()
  const chart = page.getByTestId('frontier-map')
  await expect(chart).toBeVisible({ timeout: 20000 })
  await expect(chart).toContainText('Initial battery charge (%)')
  await expect(chart).toContainText('Blackout duration (hours)')
  await expect(chart).toContainText('20%')
  await expect(chart.locator('.chart-x-tick').first()).toHaveText('20%')
  for (const label of ['CRITICAL POWER SURVIVES', 'CRITICAL POWER FAILS', 'AI-SUGGESTED, PHYSICS-VERIFIED SCENARIO', 'CURRENT SCHOOL SCENARIO']) {
    await expect(chart.getByLabel('Chart legend')).toContainText(label)
  }
  const marker = page.getByTestId('current-scenario-marker')
  await expect(marker).toHaveAccessibleName(/80% charge, 16 h blackout/)
  await marker.click()
  await expect(page.getByTestId('cell-inspector')).toContainText('YOUR EXACT SCHOOL RUN')
  await expect(chart).toContainText('between sampled cells')
  const first = chart.locator('.frontier-cell').first()
  await first.focus()
  await first.press('ArrowRight')
  await expect(chart.locator('.frontier-cell').nth(1)).toBeFocused()
  await expect(page.getByTestId('cell-inspector')).toContainText('Physics verified')

  const predictionResponse = page.waitForResponse(response => response.url().endsWith('/api/v1/fragility/predict') && response.ok())
  const candidatesResponse = page.waitForResponse(async response => response.url().endsWith('/api/v1/fragility/frontier') && response.ok() && (await response.json()).model_version)
  await page.getByRole('button', { name: 'NEXT STEP' }).click()
  const prediction = await (await predictionResponse).json()
  const suggestions = await (await candidatesResponse).json()
  expect(prediction.estimate).not.toBeNull()
  await expect(page.getByTestId('ai-score')).toHaveText(prediction.estimate.synthetic_failure_score.toFixed(4))
  await expect(page.getByTestId('ai-comparison')).toContainText(prediction.estimate.model_version)
  await expect(page.getByTestId('ai-comparison')).toContainText(prediction.estimate.predicted_failure ? 'FAILURE' : 'SURVIVAL')
  await expect(page.getByTestId('ai-comparison')).toContainText('FAILURE AT 9.12 h')
  if (prediction.estimate.outside_training_domain) await expect(page.getByTestId('ai-ood')).toBeVisible()
  if (prediction.estimate.high_uncertainty) await expect(page.getByTestId('ai-uncertainty')).toBeVisible()
  await expect(page.getByTestId('analysis-report')).toContainText('not the probability of a real-world grid outage')
  await expect(page.getByTestId('verified-ml')).toContainText(`All ${suggestions.verified_candidates.length} were independently evaluated`)
  const repeated = page.waitForResponse(response => response.url().endsWith('/api/v1/fragility/predict') && response.ok())
  await page.getByTestId('run-ai').click()
  const rerun = await repeated
  expect(rerun.request().postDataJSON()).toEqual(prediction.input)
  expect((await rerun.json()).input_hash).toBe(prediction.input_hash)
  await page.getByTestId('analysis-step-1').click()
  await expect(page.getByTestId('ai-marker')).toHaveCount(suggestions.verified_candidates.length)
  await page.getByRole('checkbox', { name: 'Show AI-suggested test cases' }).uncheck()
  await expect(page.getByTestId('ai-marker')).toHaveCount(0)
  await page.getByRole('checkbox', { name: 'Show AI-suggested test cases' }).check()
  await expect(page.getByTestId('ai-marker')).toHaveCount(suggestions.verified_candidates.length)
  await page.keyboard.press('Escape')
  await expect(page.getByTestId('analysis-report')).toHaveCount(0)
  await expect(page.getByTestId('open-analysis')).toBeFocused()
  await expect(page.locator('main')).toHaveAttribute('data-phase', 'BLACKOUT')
})

test('responsive report fits laptops, projector and narrow screens; dialog contains keyboard focus', async ({ page }) => {
  await school(page)
  for (const size of [{ width: 1366, height: 768 }, { width: 1440, height: 900 }, { width: 1920, height: 1080 }, { width: 390, height: 844 }]) {
    await page.setViewportSize(size)
    await expect.poll(async () => (await page.locator('main').boundingBox())?.height).toBe(size.height)
    const overview = await page.getByTestId('physics-panel').boundingBox()
    expect(overview!.x).toBeGreaterThanOrEqual(0)
    expect(overview!.x + overview!.width).toBeLessThanOrEqual(size.width)
    const facility = await page.getByTestId('site-school').boundingBox()
    expect(overview!.y + overview!.height).toBeLessThanOrEqual(facility!.y)
    await page.getByTestId('show-frontier').click()
    const report = page.getByTestId('analysis-report')
    await expect(page.getByTestId('current-scenario-marker')).toBeVisible({ timeout: 20000 })
    const bounds = await report.boundingBox()
    expect(bounds!.x).toBeGreaterThanOrEqual(0)
    expect(bounds!.y).toBeGreaterThanOrEqual(0)
    expect(bounds!.width).toBeLessThanOrEqual(size.width)
    expect(bounds!.height).toBeLessThanOrEqual(size.height)
    expect(await report.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
    expect(await report.locator('.analysis-scroll').evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
    const close = page.getByRole('button', { name: 'Close school analysis' })
    await close.focus()
    await page.keyboard.press('Shift+Tab')
    expect(await page.evaluate(() => document.activeElement?.closest('dialog') !== null)).toBe(true)
    await close.click()
    await expect(page.getByTestId('show-frontier')).toBeFocused()
  }
})

test('axes, exact marker and verdict adapt to a real nondefault profile scenario', async ({ page, request }) => {
  const response = await request.post('/api/v1/simulations', { data: {
    duration_hours: 12.4, battery: { initial_soc: .72, minimum_soc: .35, maximum_soc: .9 },
    load: { critical_profile_kw: Array(50).fill(1.7) },
  } })
  expect(response.ok()).toBe(true)
  const actual = await response.json()
  // Replay an actual API calculation, not a fabricated scientific fixture.
  await page.route('**/api/v1/simulations', route => route.fulfill({ json: actual }))
  await school(page)
  await expect(page.getByTestId('physics-panel')).toContainText('12.4-hour blackout')
  await expect(page.getByTestId('first-failure')).toHaveText(`${Number(actual.summary.critical_survival_hours.toFixed(2))} h`)
  await page.getByTestId('show-frontier').click()
  await expect(page.getByTestId('frontier-map')).toBeVisible({ timeout: 20000 })
  await expect(page.locator('.chart-x-tick').first()).toHaveText('35%')
  await expect(page.locator('.chart-x-tick').last()).toHaveText('90%')
  await expect(page.locator('.chart-y-tick').last()).toHaveText('12.4')
  await expect(page.getByTestId('current-scenario-marker')).toHaveAccessibleName(/72% charge, 12.4 h blackout/)
  await expect(page.getByTestId('frontier-map')).toContainText('between sampled cells')
})

test('survival is limited to the actual horizon and early failure does not imply continuous loss', async ({ page, request }) => {
  const survivalResponse = await request.post('/api/v1/simulations', { data: { duration_hours: 4 } })
  const survived = await survivalResponse.json()
  expect(survived.summary.survived_full_window).toBe(true)
  await page.route('**/api/v1/simulations', route => route.fulfill({ json: survived }))
  await school(page)
  await expect(page.locator('.compact-verdict')).toContainText('YES')
  await page.getByTestId('open-analysis').click()
  await expect(page.getByTestId('outage-verdict')).toContainText('No critical failure is observed')
  await expect(page.getByTestId('outage-verdict')).toContainText('beyond 4 h has not been established')
  await page.getByRole('button', { name: 'Close school analysis' }).click()
  await page.getByTestId('reset-scene').click()
  const recoveryResponse = await request.post('/api/v1/simulations', { data: {
    duration_hours: .5, battery: { initial_soc: .2 }, solar: { profile_kw: [0, 10], islanding_capable: true },
  } })
  const recovery = await recoveryResponse.json()
  expect(recovery.summary.critical_survival_hours).toBe(0)
  await page.unroute('**/api/v1/simulations')
  await page.route('**/api/v1/simulations', route => route.fulfill({ json: recovery }))
  await page.getByTestId('disconnect-grid').click()
  await expect(page.getByTestId('first-failure')).toHaveText('0 h')
  await page.getByTestId('open-analysis').click()
  await expect(page.locator('.supply-fails')).toHaveCount(1)
  await expect(page.locator('.supply-survives')).toHaveCount(1)
  await expect(page.getByTestId('outage-verdict')).toContainText('0.5 h remain')
  await page.getByRole('button', { name: 'Close school analysis' }).click()
  await page.getByTestId('reset-scene').click()
  const connectedResponse = await request.post('/api/v1/simulations', { data: { duration_hours: .5, grid: { online: true } } })
  await page.unroute('**/api/v1/simulations')
  await page.route('**/api/v1/simulations', route => route.fulfill({ response: connectedResponse }))
  await page.getByTestId('disconnect-grid').click()
  await expect(page.getByTestId('physics-panel')).toBeVisible()
  await page.getByTestId('open-analysis').click()
  await expect(page.locator('.trace-scale')).toContainText('0 h / grid connected')
})

test('unavailable AI and suggestions preserve the physical verdict and map', async ({ page }) => {
  await page.route('**/api/v1/fragility/predict', route => route.fulfill({ status: 503, body: 'Unavailable' }))
  await page.route('**/api/v1/fragility/frontier', async route => {
    const body = route.request().postDataJSON()
    if (!body.include_ml) return route.continue()
    const response = await route.fetch({ postData: { ...body, include_ml: false } })
    const data = await response.json()
    await route.fulfill({ json: { ...data, warnings: ['Requested ML proposals are unavailable; authoritative physics map retained.'] } })
  })
  await school(page)
  await page.getByTestId('show-frontier').click()
  await expect(page.getByTestId('current-scenario-marker')).toBeVisible({ timeout: 20000 })
  await page.getByTestId('analysis-step-2').click()
  await page.getByTestId('run-ai').click()
  await expect(page.getByTestId('analysis-report')).toContainText('AI analysis is unavailable')
  await page.unroute('**/api/v1/fragility/predict')
  await page.route('**/api/v1/fragility/predict', async route => {
    const actual = await (await route.fetch()).json()
    await route.fulfill({ json: { ...actual, estimate: null, model_version: null, warnings: ['ML unavailable; authoritative physics evaluation used.'] } })
  })
  await page.getByTestId('run-ai').click()
  await expect(page.getByTestId('ai-comparison')).toContainText('MODEL UNAVAILABLE')
  await expect(page.getByTestId('ai-comparison')).toContainText('FAILURE AT 9.12 h')
  await expect(page.getByTestId('ai-score')).toHaveCount(0)
  await page.getByTestId('verify-ml').click()
  await expect(page.getByTestId('proposals-unavailable')).toBeVisible()
  await page.getByTestId('analysis-step-1').click()
  await expect(page.getByTestId('current-scenario-marker')).toBeVisible()
  await expect(page.getByTestId('ai-marker')).toHaveCount(0)
})
